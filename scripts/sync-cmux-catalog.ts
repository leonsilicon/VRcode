#!/usr/bin/env bun
/** Pin Quest action forms and the Mac allowlist to cmux's public operation inventory. */
import { mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { parseArgs } from "node:util";
import { repoRoot } from "./lib/process";

const revision = "adc65e8aa59f2347b68cb8014c0980d634f19bc7";
const compactJSON = (value: unknown) => JSON.stringify(value).replace(/[\u0080-\uffff]/g, (char) => `\\u${char.charCodeAt(0).toString(16).padStart(4, "0")}`);

export async function outputs(source: string) {
  const spec = await Bun.file(resolve(source, "cmux-tui/spec/resource-operations-v2.json")).json();
  const inventory = await Bun.file(resolve(source, "cmux-tui/spec/inventory.json")).json();
  const catalog = { protocol: spec.protocol, revision, operations: spec.operations, types: spec.types };
  const operations = Object.entries(spec.operations) as [string, { class: string }][];
  let swift = "// Generated by scripts/sync-cmux-catalog.ts. Do not edit.\nlet cmuxOperationClasses: [String: String] = [\n";
  swift += operations.map(([name, op]) => `  ${JSON.stringify(name)}: ${JSON.stringify(op.class)},\n`).join("") + "]\n";
  let doc = `# cmux interaction coverage\n\nSource: [cmux public API and UI inventory](https://github.com/manaflow-ai/cmux/tree/${revision}/cmux-tui/spec), pinned to the same SDK revision as xmux. Regenerate with \`bun scripts/sync-cmux-catalog.ts /path/to/cmux\`.\n\n`;
  doc += `All ${operations.length} public transported operations are carried over one persistent Unix-socket connection per Quest control connection. Reads, mutations, streams, cancellation, and connection-scoped viewer leases use the original protocol. Mutation idempotency keys survive transport unchanged; mutations are never automatically replayed after a disconnect.\n\n`;
  doc += "The Quest Actions panel provides common controls and searchable forms for the full catalog. Selectors use explicit resource IDs from a live session snapshot. Logical cmux focus changes daemon state; it does not activate any macOS app or window.\n\n";
  doc += "## Public operations\n\n| Operation | Kind | Quest route |\n| --- | --- | --- |\n";
  for (const [name, op] of operations) doc += `| \`${name}\` | ${op.class} | Actions → All actions → generated form |\n`;
  doc += "\n## cmux frontend actions\n\nThese are the complete native TUI and context-menu inventories, including actions that belong to a frontend or an external provider rather than the session API.\n\n| Surface | Action | Upstream route / ownership |\n| --- | --- | --- |\n";
  for (const surface of ["tui_actions", "menu_actions"]) {
    for (const action of inventory[surface]) {
      const route = typeof action.route === "string" ? action.route : compactJSON(action.route);
      doc += `| ${surface === "tui_actions" ? "Keyboard" : "Menu"} | ${action.variant} | ${action.classification}: ${route.replaceAll("|", "/")} |\n`;
    }
  }
  doc += "\n## Frontend and external boundaries\n\nClipboard copy/paste and selectable/searchable terminal text run on the Quest; explicit Mac clipboard transfer uses background NSPasteboard access. The existing Quest settings own window presentation, movement, and text sizing. Disconnect closes the Quest connection. Browser control operations are transported, but xmux has no browser-frame renderer; this change does not claim a Quest browser view. Provider-managed machines/workspaces, local plugin installation, SSH-machine catalogs, native sidebar profiles, and native window presentation belong to separate provider or frontend APIs, not cmux.protocol/2; they are inventoried above rather than sent as fake terminal keystrokes. Terminal selection is not settable through the public API: use Quest's selectable text/history view instead of depending on a selection in a Mac frontend.\n";
  return {
    "settings-ui/src/main/assets/cmux-catalog.json": compactJSON(catalog) + "\n",
    "mac/Sources/vrcode-mac/CmuxCatalog.swift": swift,
    "docs/cmux-interactions.md": doc,
    "settings-ui/src/main/assets/cmux-catalog.LICENSE": await Bun.file(resolve(source, "LICENSE")).text(),
  };
}

export async function main(argv = Bun.argv.slice(2)) {
  const { values, positionals } = parseArgs({ args: argv, allowPositionals: true, options: { check: { type: "boolean" }, help: { type: "boolean" } } });
  const usage = "Usage: bun scripts/sync-cmux-catalog.ts /path/to/cmux [--check]";
  if (values.help) { console.log(usage); return; }
  if (positionals.length !== 1) throw new Error(usage);
  const stale: string[] = [];
  for (const [relative, content] of Object.entries(await outputs(resolve(positionals[0])))) {
    const path = resolve(repoRoot, relative);
    if (values.check) {
      if (!await Bun.file(path).exists() || await Bun.file(path).text() !== content) stale.push(relative);
    } else {
      await mkdir(dirname(path), { recursive: true });
      await Bun.write(path, content);
    }
  }
  if (stale.length) throw new Error("Stale cmux catalog: " + stale.join(", "));
}

if (import.meta.main) main().catch((error) => { console.error(`sync-cmux-catalog: ${error.message}`); process.exitCode = 1; });
